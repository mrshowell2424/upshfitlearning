/**
 * What the hub actually holds, counted from the content.
 *
 * src/lib/constants/totals.ts exists because the pricing page once
 * advertised 2,688 resources while the matcher counted 2,760, and a number
 * a teacher is asked to pay against should not drift. The same thing was
 * about to happen on a much bigger scale: the home page now has a reading
 * library to describe — mysteries, articles, passages, word ladders,
 * spelling banks — and every one of those numbers grows when somebody
 * writes more.
 *
 * So they are counted rather than typed, and check-generated.mjs fails if
 * the committed file is not what this produces today.
 *
 *   bun run scripts/build-hub-counts.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(`scripts/${f}`, "utf8"));

const mysteries = read("reading-mysteries.json").cases.length;
const articles = read("reading-articles.json").articles.length;
// Every concept has a passage at three reading levels, so the number of
// passages a teacher can print is the concepts times the levels.
const passagesFile = read("reading-passages.json");
const concepts = Object.keys(passagesFile.passages).length;
const levels = Object.keys(passagesFile.levels).length;
const sequence = read("reading-sequence.json").sequence.length;
const ladders = Object.keys(read("reading-word-ladders.json").ladders).length;
const spelling = read("reading-spelling.json").patterns.length;
const heartWords = read("reading-heart-words.json").words.length;
const threads = read("reading-threads.json").threads.length;
const sentenceLab = read("reading-sentence-lab.json").items.length;
const morphemes = read("reading-morphology.json").morphemes.length;
const writingPassages = Object.keys(read("reading-writing-passages.json")).filter((k) => k[0] !== "_").length;
const multisyllabic = read("reading-multisyllabic.json");
const msWords = Object.values(multisyllabic.words).reduce((n, b) => n + b.real.length + b.one.length, 0);
const writingTypes = read("reading-writing-types.json").types.length;

const counts = {
  _note:
    "What the hub holds, counted from the content rather than typed into a page. Generated by scripts/build-hub-counts.mjs; do not hand-edit. check-generated.mjs fails if this has drifted from what the builder produces.",
  mysteries,
  // Each case is written twice: one culprit, or three a child can argue for.
  mysteryVersions: mysteries * 2,
  articles,
  // Every article is written at two Lexile levels.
  articleVersions: articles * 2,
  concepts,
  passages: concepts * levels,
  passageLevels: levels,
  sequence,
  ladders,
  spelling,
  heartWords,
  threads,
  sentenceLab,
  morphemes,
  writingPassages,
  writingTypes,
  multisyllabicWords: msWords,
};

writeFileSync("scripts/reading-hub-counts.json", JSON.stringify(counts, null, 1) + "\n");
const shown = Object.entries(counts).filter(([k]) => k[0] !== "_");
console.log(shown.map(([k, v]) => `${k}: ${v}`).join("\n"));
