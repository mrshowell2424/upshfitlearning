/**
 * Every multisyllabic word in the bank, divided, with the rule and the
 * syllable types named.
 *
 * WHY PRECOMPUTED. The division needs a pronouncing dictionary to settle a
 * VCV word, and that table is 180 KB. A lesson page needs the answer for ten
 * words, not the machinery for ten thousand, so the answers are worked out
 * here and the page reads them.
 *
 * WHAT A TEACHER NEEDS FROM THE KEY is not only where the word chops. It is
 * which rule put the line there and what kind of syllable each piece is,
 * because that is what a child is being taught to notice. So each entry
 * carries all three.
 *
 * UNCERTAIN DIVISIONS ARE MARKED rather than hidden. 41 words in the bank are
 * still a guess -- the dictionary does not have them, or the spelling defeats
 * it -- and a key that presents a guess as an answer is worse than one that
 * says it is unsure.
 *
 *   bun run scripts/build-syllable-splits.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { splitWord } from "./lib/syllable-split.mjs";
import { CONCEPTS } from "./lib/continuum-pools.mjs";

const MULTI = JSON.parse(readFileSync("scripts/reading-multisyllabic.json", "utf8")).words;
const PRON = JSON.parse(readFileSync("scripts/lib/vowel-length.json", "utf8"));
const VOWEL = PRON.words;
/** The letters "ng" spelling two sounds: finger and danger, not singer. */
const NG_SPLIT = new Set(PRON.ngSplit ?? []);

const real = new Set();
for (const list of Object.values(MULTI)) {
  for (const w of list.one ?? []) real.add(String(w).toLowerCase());
  for (const w of list.real ?? []) real.add(String(w).toLowerCase());
}
// The continuum review's own words too, so a P11 sheet can show how reptile
// and escape divide. They are real words that happen not to be in the bank.
for (const c of CONCEPTS) {
  if (c.kind === "letters") continue;
  for (const w of c.real) real.add(String(w).toLowerCase());
}

const isWord = (w) => real.has(w);
const firstVowelLength = (w) => VOWEL[w] ?? null;
const splitsNg = (w) => NG_SPLIT.has(w);

/** How to say the rule to a child, rather than its shorthand. */
const RULE_TEXT = {
  compound: "Two small words joined. Divide between them.",
  prefix: "A prefix at the front. Divide after it.",
  suffix: "A suffix at the end. Divide before it.",
  "consonant-le": "Count back three. The consonant plus le is the last syllable.",
  "V/V": "Two vowels that are not a team. Divide between them.",
  "VC/CV": "Two consonants in the middle. Divide between them.",
  "V/CV": "One consonant in the middle and the first vowel is long. It goes with the second syllable.",
  "VC/V": "One consonant in the middle and the first vowel is short. It stays with the first syllable.",
  "V/CCV": "The two consonants start the second syllable together, so they are not split.",
  "VC/CCV": "Three consonants in the middle. Divide after the first.",
  "VC/CCCV": "Four consonants in the middle. Divide after the first.",
};

const out = {};
let certain = 0;
let guessed = 0;
const byRule = {};

for (const w of [...real].sort()) {
  if ((w.match(/[aeiouy]+/g) || []).length < 2) continue;
  const r = splitWord(w, isWord, firstVowelLength, splitsNg);
  if (!r) continue;
  // Stored tight, because this file is read by a page that is already large.
  // The parts joined by a hyphen, the rule key, the syllable types joined by
  // a comma, and "?" only where the division is a guess. The wording of each
  // rule lives in `rules` once rather than on every word, which is what made
  // the first version of this file 920 KB.
  out[w] = [r.parts.join("-"), r.rule, r.types.join(","), r.certain === false ? "?" : ""]
    .join("|")
    .replace(/\|+$/, "");
  if (r.certain === false) guessed++;
  else certain++;
  byRule[r.rule] = (byRule[r.rule] ?? 0) + 1;
}

writeFileSync(
  "scripts/reading-syllable-splits.json",
  JSON.stringify(
    {
      _note:
        "Every multisyllabic word in the reading bank, divided into syllables. Each value is \"parts|rule|types|?\" -- the syllables joined by hyphens, the rule key into `rules`, the syllable types, and a trailing ? only where the division is a guess rather than settled by the pronouncing dictionary. Packed this way because the page that reads it is already large. Generated by scripts/build-syllable-splits.mjs; do not hand-edit.",
      rules: RULE_TEXT,
      words: out,
    },
  ) + "\n",
);

console.log(`${Object.keys(out).length} words divided`);
console.log(`  ${certain} settled, ${guessed} a guess (marked sure:false)`);
console.log("\nby rule:");
for (const [k, n] of Object.entries(byRule).sort((a, b) => b[1] - a[1])) {
  console.log(`  ${k.padEnd(14)} ${String(n).padStart(5)}`);
}
