/**
 * Fold the per-grade maths case files into scripts/math-cases.json.
 *
 * The reading mysteries work this way and these are their maths cousins: a
 * situation, the information you are given, a question, and candidate
 * answers. Two versions of each. In the solve version the given numbers
 * settle it and every other answer is ruled out by a line a child can point
 * to. In the debate version a line has been changed or taken away, and more
 * than one answer holds up if the student can say what their number assumes.
 *
 * Written by hand rather than generated, because a case worth arguing about
 * is an authoring job. What is not left to trust is the arithmetic:
 * scripts/check-math-cases.mjs re-derives every solve answer from the
 * expression the case carries, and holds the structure to its rules.
 *
 *   bun run scripts/merge-math-cases.mjs
 *
 * A grade file replaces that grade wholesale, so running this twice is the
 * same as running it once.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const PREQ = JSON.parse(readFileSync("scripts/math-prerequisites.json", "utf8"));
const GRADES = PREQ.grades;
const OUT = "scripts/math-cases.json";

const byGrade = new Map();
for (let g = 0; g < GRADES.length; g++) {
  const path = `scripts/math-cases/g${g}.json`;
  if (!existsSync(path)) continue;
  const cases = JSON.parse(readFileSync(path, "utf8"));
  for (const c of cases) {
    if (c.grade !== g) throw new Error(`${path} holds a grade ${c.grade} case`);
  }
  if (cases.length) byGrade.set(g, cases);
}

const order = [...byGrade.keys()].sort((a, b) => a - b);
const merged = order.flatMap((g) => byGrade.get(g));
if (!merged.length) throw new Error("no grade files found; nothing to merge");

writeFileSync(
  OUT,
  JSON.stringify({
    _note:
      "Maths reasoning cases: a situation, the information given, a question and candidate answers, in two versions. Solve, where the numbers settle it and every wrong answer is ruled out by a line of the problem. Debate, where a line has been changed and more than one answer holds up if the student says what it assumes. Written by hand in scripts/math-cases/g<N>.json and folded together by scripts/merge-math-cases.mjs; do not edit this file by hand. scripts/check-math-cases.mjs re-derives every solve answer and holds the structure to its rules.",
    grades: GRADES,
    cases: merged,
  }, null, 1) + "\n",
);

console.log(
  `${merged.length} cases across ${order.length} grades: ${order.map((g) => GRADES[g]).join(", ")}`,
);
