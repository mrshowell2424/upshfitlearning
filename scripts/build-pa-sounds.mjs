/**
 * The sounds in a word. Vendored, from the CMU pronouncing dictionary.
 *
 * WHY THIS EXISTS. The phonemic awareness drill is spoken: a teacher says
 * "take /s/ off 'stop'" and a child answers out loud. Generating those items
 * from spelling alone does not work, and not in a way that is obvious until
 * you read the output. Letters say that "she" without /s/ is "he", that
 * "bone" with /n/ for /b/ is "none", that "find" without /d/ is "fin", that
 * "love" and "move" rhyme and that "season" is "sea" plus "son". Every one of
 * those is wrong out loud, and a teacher reading them off a card has to mark
 * a right answer wrong.
 *
 * Spelling rules can get most of the way there -- the generator still uses
 * them to pick candidates, because they are cheap -- but only the sounds can
 * settle it. So each candidate is proved against this: take the first phoneme
 * off the word and what is left has to BE the phonemes of the answer, exactly.
 *
 * ONLY THE WORDS THIS REPO USES are kept, the same as vowel-length.json, so
 * the vendored file stays small and the build needs no 3.6 MB download.
 * Re-run with the dictionary path when new words are added:
 *
 *   bun run scripts/build-pa-sounds.mjs <path-to-cmudict.dict>
 *
 * The dictionary is public domain, from https://github.com/cmusphinx/cmudict
 */
import { readFileSync, writeFileSync } from "node:fs";
import { CONCEPTS } from "./lib/continuum-pools.mjs";

const dictPath = process.argv[2];
if (!dictPath) {
  console.error("usage: bun run scripts/build-pa-sounds.mjs <path-to-cmudict.dict>");
  console.error("  get it from https://github.com/cmusphinx/cmudict (public domain)");
  process.exit(1);
}

const SEQ = JSON.parse(readFileSync("scripts/reading-sequence.json", "utf8")).sequence;
const PASS = JSON.parse(readFileSync("scripts/reading-passages.json", "utf8")).passages;
const HEART = JSON.parse(readFileSync("scripts/reading-heart-words.json", "utf8")).words;
const MULTI = JSON.parse(readFileSync("scripts/reading-multisyllabic.json", "utf8")).words;

/** Every word any part of this repo might put in front of a child. */
const want = new Set();
const add = (w) => {
  const x = String(w).toLowerCase();
  if (/^[a-z]+$/.test(x) && x.length >= 2) want.add(x);
};
for (const l of SEQ) (l.words || []).forEach(add);
for (const k of Object.keys(PASS)) {
  for (const g of ["g2", "g3", "g4"]) {
    const t = PASS[k] && PASS[k][g];
    if (!t) continue;
    for (const para of t.paras || []) {
      for (const w of String(para).match(/[A-Za-z']+/g) || []) add(w.replace(/'/g, ""));
    }
  }
}
for (const c of CONCEPTS) (c.real || []).forEach(add);
for (const h of HEART) add(h.word);
for (const k of Object.keys(MULTI)) (MULTI[k].real || []).forEach(add);

/*
 * One pronunciation per word, and only where the dictionary gives one.
 *
 * A word with two readings is left out entirely rather than picked between.
 * "live", "read", "bow" and "wind" are each two words wearing one spelling,
 * and a drill that assumes either one is wrong half the time it is used.
 */
const seen = new Map();
const twice = new Set();
for (const line of readFileSync(dictPath, "utf8").split("\n")) {
  const m = line.match(/^([a-z']+)(\(\d+\))?\s+(.+)$/);
  if (!m) continue;
  const word = m[1].replace(/'/g, "");
  if (!want.has(word)) continue;
  // The (2) and (3) forms are alternative pronunciations of the same word.
  if (m[2]) { twice.add(word); continue; }
  // Stress digits off: this asks what the sounds are, not which is stressed.
  seen.set(word, m[3].trim().split(/\s+/).map((x) => x.replace(/\d/g, "")).join(" "));
}
for (const w of twice) seen.delete(w);

const words = {};
for (const w of [...seen.keys()].sort()) words[w] = seen.get(w);

writeFileSync(
  "scripts/lib/pa-sounds.json",
  JSON.stringify({
    _note:
      "The phonemes of every word this repo uses, from the CMU pronouncing dictionary (public domain), with stress marks removed. Words the dictionary lists more than one pronunciation for are left out, because a drill cannot assume which one a child means: live, read, bow and wind are each two words sharing a spelling. Used to prove every phonemic awareness item is true out loud rather than only on paper. Generated by scripts/build-pa-sounds.mjs; do not hand-edit.",
    source: "https://github.com/cmusphinx/cmudict",
    words,
  }, null, 1) + "\n",
);

console.log(`${Object.keys(words).length} words of ${want.size} wanted`);
console.log(`  ${twice.size} left out for having more than one pronunciation`);
